#include <iostream>

int main() {
    using std::cout;
    using std::endl;
    using std::string;

    // Integer (Whole Number)
    int x = 5; // Declaration
    int y = 6;
    int sum = x + y;
    int age = 24;
    int year = 2025;
    int days = 7;

    cout << "x = " << x << endl;
    cout << "y = " << y << endl;
    cout << "sum = " << sum << endl;
    cout << "age = " << age << endl;
    cout << "year = " << year << endl;
    cout << "days = " << days << endl;


    // Double (decimal number)
    double price = 10.99;
    double gpa = 2.5;
    double temp = 25.1;

    cout << "price = " << price << endl;
    cout << "gpa = " << gpa << endl;
    cout << "temp = " << temp << endl;


    // Single Character
    char grade = 'A';
    char initial = 'B';
    char currency = '$';

    cout << "grade = " << grade << endl;
    cout << "initial = " << initial << endl;
    cout << "currency = " << currency << endl;


    // Boolean Value
    bool student = false;
    bool ppower = true;
    bool forSale = true;


    // String (Sequence of Text)
    string name = "Bro";
    string day = "Friday";
    string food = "Pizza";
    string Address = "123 Pennsylvania Ave.";
    
    cout << "Hello " << name << endl;
    cout << "You are " << age << " years old." << endl;
    
    string greeting = "Hello";
    


    return 0;
}